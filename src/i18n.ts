import { Schema } from "effect"

export const LanguageSchema = Schema.Literals(["de", "en"])
export type Language = typeof LanguageSchema.Type

export const isLanguage = (value: unknown): value is Language => value === "de" || value === "en"

export const detectBrowserLanguage = (): Language => {
  if (typeof navigator === "undefined" || typeof navigator.language !== "string") {
    return "en"
  }
  return navigator.language.toLowerCase().startsWith("de") ? "de" : "en"
}

export const getDocumentLanguage = (): Language => {
  if (typeof document === "undefined") {
    return detectBrowserLanguage()
  }
  const lang = document.documentElement.lang.toLowerCase()
  if (lang.startsWith("de")) {
    return "de"
  }
  if (lang.startsWith("en")) {
    return "en"
  }
  return detectBrowserLanguage()
}

export const applyLanguageToDocument = (language: Language): void => {
  if (typeof document !== "undefined") {
    document.documentElement.lang = language
  }
}

